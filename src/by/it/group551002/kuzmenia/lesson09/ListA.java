    @Override
    public String toString() {
        String out = "[";
        int i = 0;
        if (size != 0) {
            out += data[0];
            i++;
        }
        for (; i < size; i++) {
            out += ", ";
            out += data[i];
        }

        out += "]";
        return out;
    }

    @Override
    public boolean add(E e) {
        if (size == data.length) {
            E[] bigger = (E[]) new Object[size + size / 2 + 1];
            for (int k = 0; k < size; k++) {
                bigger[k] = data[k];
            }
            data = bigger;
        }
        data[size] = e;
        size++;
        return true;
    }

    @Override
    public E remove(int index) {
        if (index < 0 || index >= size) {
            throw new IndexOutOfBoundsException();
        }

        E removed = data[index];
        for (int k = index; k < size - 1; k++) {
            data[k] = data[k + 1];
        }
        size--;
        data[size] = null;
        return removed;
    }

    @Override
    public int size() {
        return size;
    }

